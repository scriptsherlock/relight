// Visual walk-through: title → intro → track → hub → level 1 solved → arcade.
import { chromium } from '@playwright/test';
const out = process.argv[2] ?? 'qa-shots';
const base = process.argv[3] ?? 'http://127.0.0.1:4180/';
const size = { width: Number(process.env.W ?? 1366), height: Number(process.env.H ?? 768) };
const browser = await chromium.launch({ executablePath: process.env.CHROME || undefined });
const page = await browser.newPage({ viewport: size });
const errors = [];
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
page.on('console', (m) => m.type() === 'error' && errors.push('console: ' + m.text()));
const shot = (n) => page.screenshot({ path: `${out}/${size.width}-${n}.png` });
await page.goto(base);
await page.waitForTimeout(1500);
await shot('01-title');
await page.getByRole('button', { name: 'Start' }).click();
await page.waitForTimeout(600);
await shot('02-intro');
await page.getByRole('button', { name: 'Skip', exact: true }).click();
await page.waitForTimeout(300);
await shot('03-track');
await page.locator('.track-card.python').click();
await page.waitForTimeout(1200);
await shot('04-hub');
// drive a bit
await page.keyboard.down('ArrowLeft');
await page.waitForTimeout(700);
await page.keyboard.up('ArrowLeft');
await shot('05-hub-drive');
await page.getByRole('button', { name: 'Districts ▾' }).click();
await page.getByRole('menuitem', { name: /The Docks/ }).click();
await page.waitForTimeout(400);
await shot('06-district');
await page.getByRole('button', { name: /Wake Up, Kilo/ }).click();
await page.waitForTimeout(1500);
await shot('07-brief');
await page.getByRole('button', { name: 'Skip', exact: true }).click();
await page.waitForTimeout(500);
// wait for python
await page.waitForSelector('.py-status.ready', { timeout: 60000 });
await shot('08-level');
// type wrong code first
await page.locator('.cm-content').click();
await page.keyboard.press('Control+A');
await page.keyboard.type('bot.move_rigth()\n');
await page.getByRole('button', { name: '▶ Run' }).click();
await page.waitForTimeout(2500);
await shot('09-error');
await page.locator('.cm-content').click();
await page.keyboard.press('Control+A');
await page.keyboard.type('bot.move_right()\nbot.move_right()\nbot.move_right()\n');
await page.getByRole('button', { name: '▶ Run' }).click();
await page.waitForTimeout(800);
await shot('10-playing');
await page.waitForTimeout(3000);
await shot('11-notyet');
await page.locator('.cm-content').click();
await page.keyboard.press('Control+End');
await page.keyboard.type('bot.move_right()\n');
await page.getByRole('button', { name: '▶ Run' }).click();
await page.waitForTimeout(4500);
await shot('12-win');
console.log(JSON.stringify(errors, null, 1));
await browser.close();
